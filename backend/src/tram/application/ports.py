from collections.abc import Iterable
from datetime import datetime
from typing import Any, Protocol

from tram.domain.series import Observation, Prediction, SpatialKey
from tram.domain.time import Horizon, Interval, Resolution

Document = dict[str, Any]


class Clock(Protocol):
    def now(self) -> datetime: ...


class Repository(Protocol):
    def healthy(self) -> bool: ...
    def dataset(self, revision: str | None) -> Document | None: ...
    def network(self, revision: str) -> Document | None: ...
    def observation_points(
        self, revision: str, profile: str, query: Document, offset: int, limit: int
    ) -> list[Document]: ...
    def create_run(
        self, owner: str, key: str, fingerprint: str, run: Document, now: datetime
    ) -> tuple[Document, bool]: ...
    def replay_run(
        self, owner: str, key: str, fingerprint: str, now: datetime
    ) -> Document | None: ...
    def run(self, run_id: str) -> Document | None: ...
    def runs(
        self, query: Document, before: datetime, offset: int, limit: int
    ) -> list[Document]: ...
    def forecast_points(
        self, run_id: str, query: Document, offset: int, limit: int
    ) -> list[Document]: ...
    def series(self, revision: str, profile: str, route_ids: list[str]) -> list[Document]: ...
    def history(
        self, revision: str, profile: str, spatial: SpatialKey, as_of: datetime
    ) -> Iterable[Observation]: ...
    def claim(self, now: datetime, lease_seconds: int, max_attempts: int) -> Document | None: ...
    def heartbeat(self, run_id: str, token: str, now: datetime, lease_seconds: int) -> bool: ...
    def complete(self, run_id: str, token: str, points: list[Document], now: datetime) -> bool: ...
    def fail(self, run_id: str, token: str, now: datetime, code: str, message: str) -> bool: ...
    def evaluation(self, evaluation_id: str) -> Document | None: ...
    def evaluations(
        self, query: Document, before: datetime, offset: int, limit: int
    ) -> list[Document]: ...
    def evaluation_points(
        self, evaluation_id: str, query: Document, offset: int, limit: int
    ) -> list[Document]: ...


class CursorCodec(Protocol):
    def encode(self, payload: Document) -> str: ...
    def decode(self, token: str) -> Document: ...


class Predictor(Protocol):
    def predict(
        self,
        history: Iterable[Observation],
        series: tuple[SpatialKey, ...],
        window: Interval,
        horizon: Horizon,
        resolution: Resolution,
        as_of: datetime,
    ) -> tuple[Prediction, ...]: ...
